/*
 * \brief  5x7 bitmap font for the fault console
 * \author Sponge OS contributors
 * \date   2026
 *
 * A minimal, self-contained glyph table. The fault console must paint
 * text WITHOUT Qt and WITHOUT a libc font stack (docs/17 §5: the
 * console is the last component standing, so it may not drag a display
 * server in behind it — and a wedged display server is exactly the
 * failure it exists to report).
 *
 * Encoding: 5 columns per glyph, one byte per column. Bit 0 of a column
 * byte is the TOP row; bit 6 the bottom row. A glyph therefore occupies
 * a 5x7 cell and renders at any integer scale.
 *
 * Coverage is deliberately limited to what the console actually prints:
 * digits, A-Z, and the five punctuation marks used in the messages.
 * Lowercase input is folded to uppercase by the renderer.
 *
 * SPDX-License-Identifier: Apache-2.0
 */

