/* SPDX-License-Identifier: LicenseRef-SpongeOS-Proprietary
 *
 * sponge_themed — theme resolver daemon (Phase 5b).
 *
 * A long-lived, signal-driven Genode component (plain base, no Qt, no
 * libc). It is the middle hop of the one-way theme pipeline:
 *
 *   vct  --[config_request]-->  sponge_configd  --[config broadcast]-->
 *   sponge_themed  --[theme report]-->  sponge-de
 *
 * What it does:
 *   - Watches sponge_configd's broadcast "config" ROM (Attached_rom_dataspace
 *     "config" + sigh; report_rom policy
 *     `label: sponge_themed -> config | report: sponge_configd -> config`).
 *   - Reads the "theme.active" key (default "default") from that ROM.
 *   - Resolves the named theme by opening a "<name>.theme" ROM module
 *     (e.g. default.theme, light.theme), staged in the boot image.
 *   - Republishes the resolved theme CONTENT verbatim via an
 *     Expanding_reporter (node "theme", label "theme"; report_rom policy
 *     `label: sponge-de -> theme | report: sponge_themed -> theme`).
 *
 * Why content (raw INI) and not parsed values:
 *   sponge_themed is Qt-free and owns no renderer. The Qt-free
 *   ThemeLoader already lives in sponge-de (where the renderer is), so
 *   themed stays a pure name->content relay: it resolves WHICH file is
 *   active and ships its bytes, and sponge-de interprets them. This
 *   keeps interpretation in exactly one place and avoids duplicating
 *   the parser across components.
 *
 * Determinism / robustness:
 *   - The report carries the theme name as the "name" attribute and the
 *     raw theme bytes as the node's decoded text content, so a watcher
 *     (sponge-de or a probe) can assert on either.
 *   - The report is regenerated only when the resolved theme NAME
 *     changes (configd already de-duplicates its broadcast; matching
 *     that keeps unrelated config writes from needlessly republishing
 *     an identical theme and re-triggering sponge-de's re-style).
 *   - An unknown theme name (no staged "<name>.theme" ROM, or a ROM
 *     open failure) is NEVER fatal: themed keeps the previously
 *     published theme and logs a warning, so the desktop never goes
 *     blank because of a typo in `vct theme apply`.
 */

