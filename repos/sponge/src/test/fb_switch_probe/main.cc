namespace Fb_switch_probe { struct Main; }

struct Fb_switch_probe::Main
{
	Genode::Env &_env;

	Timer::Connection _timer { _env };

	/* pkgd's dedicated probe channel: report_rom is single-writer per
	 * label and the product media already spends `request` on
	 * alpha_probe and `launcher_request` on the desktop, so this probe
	 * uses the optional `<probe_request/>` slot
	 * (sponge_pkgd: _handle_probe_request). */
	Sponge::Backend::ReportRomClient _pkgd {
		_env, "probe_request", "probe_result" };

	Genode::Attached_rom_dataspace _driver_state { _env, "driver_runtime_state" };
	Genode::Attached_rom_dataspace _config_rom    { _env, "config" };

	Capture::Connection                _capture { _env, "fb_switch_probe" };
	Genode::Constructible<Genode::Attached_dataspace> _cap_ds { };

	using Pixel = Genode::Pixel_rgb888;

	/* Local monotonic clock. Timer::Connection has no read(), and the
	 * only thing these deadlines need is a count of the time THIS probe
	 * has slept, so the counter is maintained by the single sleep
	 * helper below rather than by querying a session. */
	unsigned _clock_ms { 0 };

	unsigned _now() const { return _clock_ms; }
	void _sleep(unsigned ms) { _timer.msleep(ms); _clock_ms += ms; }

	/* ---- config ---- */

	Genode::String<64> _active    { "fb_vesa" };
	Genode::String<64> _alternate { "fb_boot" };
	unsigned           _timeout_ms { 120000 };
	unsigned           _settle_ms  { 4000 };
	unsigned           _screen_w   { 1024 };
	unsigned           _screen_h   { 768 };

	/*
	 * The nitpicker background (docs: the product media's
	 * `+ background | color: #1e1e2e`). A pixel equal to it in all
	 * three channels counts as "nothing rendered there"; the alpha
	 * byte is deliberately ignored because the probe compares RGB only
	 * — alpha_probe's own gate compares the packed word and therefore
	 * treats any opaque background pixel as a non-background one, which
	 * is a weakness this oracle does not share.
	 */
	struct Bg { unsigned char r { 0x1e }, g { 0x1e }, b { 0x2e }; };
	Bg const _bg { };

	Main(Genode::Env &env) : _env(env) { }

	void _run();
	void _parse_config();

	/* ---- helpers ---- */

	/*
	 * driver_runtime's state report is HID, not XML: a Genode sandbox
	 * Generator serializes in HID and an Xml_node read of it silently
	 * yields nothing (the same trap sponge_pkgd documents in
	 * _read_budget).
	 */
	bool _state_lists(char const *child)
	{
		_driver_state.update();
		if (!_driver_state.valid() || _driver_state.size() == 0)
			return false;
		bool found { false };
		Genode::Hid_node const root(Genode::Const_byte_range_ptr(
			_driver_state.local_addr<char const>(), _driver_state.size()));
		root.for_each_sub_node([&] (Genode::Hid_node const &n) {
			if (n.has_type("child") &&
			    n.attribute_value("name", Genode::String<64>()) ==
			    Genode::String<64>(child))
				found = true;
		});
		return found;
	}

	/* Rendered-pixel census over a fixed grid. Sampling rather than
	 * hashing keeps the oracle honest about what it proves and cheap
	 * enough to run every 250 ms. */
	struct Census
	{
		unsigned sampled   { 0 };
		unsigned rendered  { 0 };
		unsigned long long checksum { 0 };

		bool rendered_enough(unsigned min) const
		{ return rendered >= min; }

		bool operator == (Census const &o) const
		{ return rendered == o.rendered && checksum == o.checksum; }
	};

	bool _census(Census &out)
	{
		if (!_cap_ds.constructed())
			return false;

		try {
			_capture.capture_at(Capture::Point(0, 0));
		} catch (...) {
			/* The display provider is gone (the fb driver was just
			 * removed): nitpicker cannot hand out a buffer for a
			 * screen that has no size. Not an error here — the caller
			 * polls and retries. */
			return false;
		}

		Pixel const *px = _cap_ds->local_addr<Pixel>();

		Census c { };
		/* A 32x20 grid: dense enough that the themed panel (top 28 px),
		 * the launcher popup and the desktop window all contribute,
		 * sparse enough that a two-sample settle check is cheap. */
		for (unsigned y = 8; y < _screen_h; y += _screen_h / 20) {
			for (unsigned x = 8; x < _screen_w; x += _screen_w / 32) {
				Pixel const p = px[y * _screen_w + x];
				c.sampled++;
				c.checksum = c.checksum * 31u
				           + unsigned(p.r()) * 7u
				           + unsigned(p.g()) * 13u
				           + unsigned(p.b());
				if (p.r() != _bg.r || p.g() != _bg.g || p.b() != _bg.b)
					c.rendered++;
			}
		}
		out = c;
		return true;
	}

	bool _wait_for_child(char const *name, bool present, unsigned budget_ms)
	{
		unsigned const deadline = _now() + budget_ms;
		for (;;) {
			if (_state_lists(name) == present)
				return true;
			if (_now() >= deadline)
				return false;
			_sleep(250);
		}
	}

	/* One pkgd op, re-sent until an answer arrives. The re-send is the
	 * driver_probe pattern and both halves matter: pkgd de-duplicates
	 * identical (op, pkg, seq) signatures, and a send that races pkgd's
	 * own attach is lost with nothing on the wire. A fresh seq per
	 * repeat makes each resend a genuinely new report, and every op
	 * used here is idempotent. */
	bool _ask(char const *op, char const *pkg, Genode::String<32> &status)
	{
		unsigned const deadline = _now() + 15000;
		while (_now() < deadline) {
			/*
			 * request() blocks until pkgd answers THIS (op, pkg) and
			 * only then does result_xml() describe it. Reading the ROM
			 * unconditionally would report the PREVIOUS answer — and
			 * that mistake made an `exclusive-conflict` refusal look
			 * like an `ok`, which is the one direction in which this
			 * probe must never be wrong.
			 */
			if (_pkgd.request(op, pkg)) {
				status = _pkgd.result_xml().attribute_value(
					"status", Genode::String<32>());
				return true;
			}
			_sleep(500);
		}
		return false;
	}

	[[noreturn]] void _fail(char const *phase, char const *detail)
	{
		Genode::error("fb-switch-probe: FAIL phase=", phase,
		              " detail=", detail);
		_env.parent().exit(1);
		Genode::sleep_forever();
	}
};


void Fb_switch_probe::Main::_parse_config()
{
	_config_rom.update();
	if (!_config_rom.valid()) return;

	char const *const base = _config_rom.local_addr<char>();
	Genode::size_t const sz  = _config_rom.size();

	bool const is_xml = (sz > 0 && base[0] == '<');
	if (is_xml) {
		Genode::Xml_node const root(base, sz);
		if (!root.has_type("config")) return;
		_active    = root.attribute_value("active",    Genode::String<64>("fb_vesa"));
		_alternate = root.attribute_value("alternate", Genode::String<64>("fb_boot"));
		_timeout_ms = root.attribute_value("timeout_ms", 120000u);
		_settle_ms  = root.attribute_value("settle_ms",  4000u);
		_screen_w   = root.attribute_value("screen_w",   1024u);
		_screen_h   = root.attribute_value("screen_h",   768u);
		return;
	}

	Genode::Hid_node const root(Genode::Const_byte_range_ptr(base, sz));
	if (!root.has_type("config")) return;
	_active    = root.attribute_value("active",    Genode::String<64>("fb_vesa"));
	_alternate = root.attribute_value("alternate", Genode::String<64>("fb_boot"));
	_timeout_ms = root.attribute_value("timeout_ms", 120000u);
	_settle_ms  = root.attribute_value("settle_ms",  4000u);
	_screen_w   = root.attribute_value("screen_w",   1024u);
	_screen_h   = root.attribute_value("screen_h",   768u);
}


void Fb_switch_probe::Main::_run()
{
	_parse_config();

	Genode::log("fb-switch-probe: active=", _active,
	            " alternate=", _alternate,
	            " screen ", _screen_w, "x", _screen_h);

	/* ---- phase 1: the display driver is a driver_runtime child ---- */
	if (!_wait_for_child(_active.string(), true, _timeout_ms))
		_fail("driver-child",
		      "driver_runtime never reported the media's fb package as a child");
	Genode::log("fb-switch-probe: driver_runtime lists child '", _active, "'");

	/* ---- phase 2: the display is really up ---- */
	_capture.buffer(Capture::Session::Buffer_attr {
		.px       = { _screen_w, _screen_h },
		.mm       = { },
		.viewport = { { 0, 0 }, { _screen_w, _screen_h } } });

	/*
	 * The dataspace is attached ONCE, from the buffer nitpicker hands
	 * out for this session. It is not re-attached per sample: a Capture
	 * session's dataspace stays valid while the session does, and after
	 * the fb swap the session SURVIVES (nitpicker keeps serving Gui
	 * clients, only its output back end disappears) — so a single
	 * attachment is also what makes the post-switch samples comparable
	 * with the baseline.
	 */
	_cap_ds.construct(_env.rm(), _capture.dataspace());

	Census     before { };
	unsigned const budget = _now() + _timeout_ms;
	while (_now() < budget) {
		if (_census(before) && before.rendered_enough(20)) break;
		_sleep(500);
	}
	if (!_census(before) || !before.rendered_enough(20))
		_fail("pre-switch-display",
		      "the composited screen carried no rendered desktop before the switch");
	Genode::log("fb-switch-probe: pre-switch frame rendered ", before.rendered,
	            "/", before.sampled, " sampled pixels");

	/* ---- phase 3: the handover itself ---- */
	Genode::String<32> status { };
	if (!_ask("remove", _active.string(), status) ||
	    status != Genode::String<32>("ok"))
		_fail("remove-active", "pkgd did not remove the running fb package");
	if (!_wait_for_child(_active.string(), false, _timeout_ms))
		_fail("remove-active", "the old driver stayed in driver_runtime");

	if (!_ask("install", _alternate.string(), status) ||
	    status != Genode::String<32>("ok"))
		_fail("install-alternate", "pkgd did not install the other fb package");
	if (!_wait_for_child(_alternate.string(), true, _timeout_ms))
		_fail("install-alternate", "the new driver never entered driver_runtime");
	Genode::log("fb-switch-probe: driver_runtime now lists child '", _alternate, "'");

	/* ---- phase 4: the display comes back and settles ---- */
	Census     after { }, last { };
	unsigned const settle_deadline = _now() + _timeout_ms;
	bool       have_last { false };
	for (;;) {
		Census c { };
		if (_census(c) && c.rendered_enough(20)) {
			if (have_last && c == last) break;   /* settled */
			last = c;
			have_last = true;
		} else {
			have_last = false;   /* still black: restart the settle count */
		}
		if (_now() >= settle_deadline)
			_fail("post-switch-display",
			      "the screen never settled on a rendered desktop after the swap");
		_sleep(_settle_ms);
	}

	after = last;
	Genode::log("fb-switch-probe: post-switch frame rendered ", after.rendered,
	            "/", after.sampled, " sampled pixels (settled)");
	Genode::log("fb-switch-probe: switch ", _active, " -> ", _alternate,
	            " complete");

	Genode::log("fb-switch-probe: PASS");
	_env.parent().exit(0);
	Genode::sleep_forever();
}


void Component::construct(Genode::Env &env)
{
	static Fb_switch_probe::Main main { env };
	main._run();
}