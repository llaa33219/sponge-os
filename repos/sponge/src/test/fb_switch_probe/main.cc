/* SPDX-License-Identifier: Apache-2.0
 *
 * fb_switch_probe — the runtime framebuffer-driver switch proof.
 *
 * The display driver is a PACKAGE (docs/17 §1): pkgd seeds one fb
 * package as a first-boot root and emits its <start> node into
 * driver_runtime, and the Tier-0 `platform` policy grants the PCI VGA
 * class under that package's own label prefix. Switching display
 * drivers is therefore a package operation with no privileged static
 * fixture involved — which is exactly the claim that needs proving, and
 * the one a log line cannot make.
 *
 * Four phases, each bounded and each reported by name on failure:
 *
 *   1. driver_runtime lists the media's fb package as a child. That
 *      state report is generated by driver_runtime's own init from its
 *      own child table, so the name can only be there if the pkgd-
 *      generated config really reached it and the driver really
 *      started.
 *   2. the display is up: a Capture oracle over the composited screen
 *      finds a rendered (non-background) desktop. Without this the
 *      later phases could "pass" on a system whose display never came
 *      up at all.
 *   3. `remove <active>` then `install <other>` moves the driver: the
 *      first child disappears from the state report, the second
 *      appears in it.
 *   4. the screen comes BACK and SETTLES. The pixel readout is
 *      re-sampled until two consecutive samples agree, and the settled
 *      frame must contain a rendered desktop again. This is what makes
 *      the claim a display claim: a driver that starts and then fails
 *      to map or blit settles to black, and a client that never
 *      repainted settles to an empty or stale frame. Neither passes.
 *
 * The exclusivity refusal (`install <other>` while one runs is
 * `exclusive-conflict`, docs/12 §4.6) is proven in the LEAN topology
 * instead, run/sponge-pkg-driver.run: here the desktop installs seven
 * packages of its own on the very same pkgd backend, and interleaving
 * those with this probe's requests makes the backend's single request
 * channel a confound rather than a proof.
 *
 * SESSIONS (minimum privilege, AGENTS.md §1.2): Timer, Report (the
 * pkgd probe_request channel), the driver_runtime_state ROM, and
 * Capture (read-only pixels). No Platform, no IO_MEM, nothing that
 * could disturb the very hardware claim under test.
 */

