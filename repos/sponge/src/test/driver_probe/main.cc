namespace {

struct Driver_probe
{
	Genode::Env &_env;

	Timer::Connection              _timer     { _env };
	Genode::Attached_rom_dataspace _config_rom { _env, "config" };

	Genode::Expanding_reporter     _request   { _env, "request", "request" };
	Genode::Attached_rom_dataspace _result    { _env, "result" };
	/* pkgd's installed-set broadcast. Not an assertion here — it is the
	 * observability marker that tells a failed run whether the backend
	 * was ever alive at all (no broadcast) or alive but silent (no
	 * result), which are very different defects. */
	Genode::Attached_rom_dataspace _installed { _env, "installed" };

	/* driver_runtime's own sandbox state report, relayed by report_rom.
	 * Opened eagerly: the scenario that builds this probe always routes
	 * it, and an unread-but-absent ROM would make the probe vacuous. */
	Genode::Attached_rom_dataspace _driver_state { _env, "driver_runtime_state" };

	Genode::String<64> _pkg          { };
	Genode::String<16> _expect_status{ "ok" };
	unsigned           _timeout_ms   { 40000 };
	bool               _expect_child { true  };

	Driver_probe(Genode::Env &env) : _env(env) { }

	void _run();
	void _parse_config();

	/* ---- primitives ---- */

	bool _result_status(Genode::String<16> &out)
	{
		if (!_result.valid()) return false;
		try {
			Genode::Xml_node const r = _result.xml();
			if (!r.has_type("result")) return false;
			if (r.attribute_value("pkg", Genode::String<128>()) !=
			    Genode::String<128>(_pkg.string()))
				return false;
			if (!r.has_attribute("status")) return false;
			out = r.attribute_value("status", Genode::String<16>());
			return true;
		} catch (Genode::Xml_node::Invalid_syntax) {
			return false;
		}
	}

	/*
	 * The state report is HID, not XML — the same trap pkgd documents for
	 * its own admission read (sponge_pkgd/main.cc::_read_budget): the
	 * sandbox Generator serializes in HID and an Xml_node read of it
	 * silently yields nothing at all.
	 */
	bool _state_lists(char const *child)
	{
		_driver_state.update();
		if (!_driver_state.valid() || _driver_state.size() == 0)
			return false;
		bool found { false };
		Genode::Hid_node const root(Genode::Const_byte_range_ptr(
			_driver_state.local_addr<char const>(), _driver_state.size()));
		root.for_each_sub_node([&] (Genode::Hid_node const &n) {
			if (n.has_type("child") &&
			    n.attribute_value("name", Genode::String<64>()) ==
			    Genode::String<64>(child))
				found = true;
		});
		return found;
	}

	void _fail(char const *phase, char const *detail)
	{
		Genode::error("driver-probe: FAIL phase=", phase, " detail=", detail);
		_env.parent().exit(1);
		Genode::sleep_forever();
	}
};


void Driver_probe::_parse_config()
{
	_config_rom.update();
	if (!_config_rom.valid()) return;

	char const *const base = _config_rom.local_addr<char>();
	Genode::size_t  const sz  = _config_rom.size();

	bool const is_xml = (sz > 0 && base[0] == '<');
	if (is_xml) {
		Genode::Xml_node const root(base, sz);
		if (!root.has_type("config")) return;
		_pkg = root.attribute_value("pkg", Genode::String<64>());
		_expect_status = root.attribute_value("expect_status", Genode::String<16>("ok"));
		_timeout_ms = root.attribute_value("timeout_ms", 40000u);
		_expect_child = root.attribute_value("expect_child", true);
		return;
	}

	Genode::Hid_node const root(Genode::Const_byte_range_ptr(base, sz));
	if (!root.has_type("config")) return;
	_pkg = root.attribute_value("pkg", Genode::String<64>());
	_expect_status = root.attribute_value("expect_status", Genode::String<16>("ok"));
	_timeout_ms = root.attribute_value("timeout_ms", 40000u);
	_expect_child = root.attribute_value("expect_child", true);
}


void Driver_probe::_run()
{
	_parse_config();

	if (Genode::strcmp(_pkg.string(), "") == 0) {
		Genode::error("driver-probe: config carries no 'pkg' attribute");
		_env.parent().exit(1);
		Genode::sleep_forever();
	}

	Genode::log("driver-probe: installing driver package '", _pkg, "'");([&](Genode::Xml_generator &g) {
		g.attribute("op",  "install");
		g.attribute("pkg", _pkg.string());
		g.attribute("seq", 1);
	});

	/*
	 * Wait for pkgd's installed-set broadcast before sending anything.
	 *
	 * The probe and pkgd construct concurrently, so a single-shot send
	 * published before pkgd has attached its "request" ROM is lost with
	 * nothing on the wire to show for it — report_rom relays reports to
	 * whoever is listening at the time, and re-publishing byte-identical
	 * content raises no signal to bring pkgd up to date afterwards. The
	 * broadcast is the readiness signal that actually exists: pkgd
	 * publishes it as the last step of its own construction, so seeing
	 * it means the request path is live.
	 */
	unsigned const iters = _timeout_ms / 100;
	Genode::String<16> status { };
	bool answered { false };
	unsigned seq { 0 };
	bool     _broadcast_seen { false };

	for (unsigned i = 0; i < iters; ++i) {
		/*
		 * The request is RE-SENT every second until an answer arrives,
		 * each time with a fresh seq. Both halves matter:
		 *
		 *   - the probe and pkgd construct concurrently, so a send that
		 *     races pkgd's own attach of the "request" ROM is lost with
		 *     nothing on the wire to show for it. Re-publishing
		 *     byte-identical content would raise no signal to bring pkgd
		 *     up to date afterwards, so the seq advances to make each
		 *     repeat a genuinely new report.
		 *   - a repeated install is idempotent (the root set is
		 *     de-duplicated and the config generator is deterministic),
		 *     so a probe that re-sends can never leave a half-applied
		 *     state behind.
		 */
		if (i % 10 == 0) {
			_request.generate_xml([&](Genode::Xml_generator &g) {
				g.attribute("op",  "install");
				g.attribute("pkg", _pkg.string());
				g.attribute("seq", ++seq);
			});
			if (i == 0)
				Genode::log("driver-probe: sending install request");
		}
		if (!_broadcast_seen) {
			_installed.update();
			if (_installed.valid() && _installed.size() > 0) {
				_broadcast_seen = true;
				Genode::log("driver-probe: pkgd broadcast seen");
			}
		}
		_result.update();
		if (_result_status(status)) { answered = true; break; }
		_timer.msleep(100);
	}

	if (!answered)
		_fail("install-result", "pkgd never answered the install request");

	if (status != _expect_status) {
		Genode::error("driver-probe: install status=", status,
		              " expected=", _expect_status);
		_env.parent().exit(1);
		Genode::sleep_forever();
	}

	Genode::log("driver-probe: install answered status=", status);

	/*
	 * A non-"ok" expectation is a refusal test (e.g. admission control
	 * refusing an oversized driver). There is nothing to look for in the
	 * state report in that case — the refusal IS the result.
	 */
	if (_expect_status != Genode::String<16>("ok")) {
		Genode::log("driver-probe: PASS (refusal as expected)");
		_env.parent().exit(0);
		Genode::sleep_forever();
	}

	if (!_expect_child) {
		Genode::log("driver-probe: PASS (child assertion skipped)");
		_env.parent().exit(0);
		Genode::sleep_forever();
	}

	for (unsigned i = 0; i < iters; ++i) {
		if (_state_lists(_pkg.string())) {
			Genode::log("driver-probe: driver_runtime lists child '", _pkg, "'");
			Genode::log("driver-probe: PASS");
			_env.parent().exit(0);
			Genode::sleep_forever();
		}
		_timer.msleep(100);
	}

	_fail("driver-state", "driver_runtime never reported the driver as a child");
}


}

void Component::construct(Genode::Env &env)
{
	static Driver_probe probe { env };
	probe._run();
}

/* Two Attached_rom_dataspace + one Timer + one Reporter on the stack of a
 * component that then sleeps forever: keep the ep thread comfortable. */
Genode::size_t Component::stack_size() { return 64 * 1024 * sizeof(Genode::addr_t); }