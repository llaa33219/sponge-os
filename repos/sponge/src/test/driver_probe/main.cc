/* SPDX-License-Identifier: Apache-2.0
 *
 * driver_probe — install-a-driver-package acceptance probe.
 *
 * The automated verification for the driver package path
 * (docs/12-package-format.md §4.5, docs/17 §1): it drives sponge_pkgd
 * through the ordinary `install` request — the exact channel `vct
 * install <driver>` writes to — and then asserts the two things that
 * actually matter and that no other signal in the system can fake:
 *
 *   1. pkgd answered `status="ok"` for the install. That answer is only
 *      produced after the admission pre-flight (the driver's declared
 *      quota fits driver_runtime's live state report) and after the
 *      driver_runtime config was regenerated with the package's <start>
 *      node.
 *
 *   2. the driver appears as a `<child name="...">` in driver_runtime's
 *      sandbox state report. That report is generated by driver_runtime's
 *      OWN init from its OWN child table, so the name can only appear
 *      there if the nested init really parsed the pkgd-generated config
 *      and really created the component. A config that was never
 *      delivered, a binary that was never staged, a quota that was
 *      clamped to nothing — every one of those failure modes leaves no
 *      <child> node, and this probe fails loudly instead of passing on
 *      the "ok" alone.
 *
 * The gate deliberately does NOT assert that the hardware bound. Whether
 * a NIC claimed an e1000, or a GPU mapped its BAR, is asserted by the
 * driver component's own log lines and gated in the run script, because
 * only the driver knows what "bound" looks like for its hardware.
 *
 * Config (HID or XML, both accepted — a child config arrives in HID from
 * init but as XML from a direct boot module):
 *
 *   config
 *     + pkg: pc_nic            # package to install (required)
 *     + expect_status: ok      # optional; non-"ok" asserts a refusal
 *     + timeout_ms: 40000      # optional; per-phase ceiling, default 40s
 *     + expect_child: yes      # optional; "no" skips the state-report
 *                              # assertion. Needed when the driver cannot
 *                              # really come up in this topology (a
 *                              # framebuffer driver with no compositor)
 *                              # but pkgd's RUNNING set is what the test
 *                              # is about.
 *
 * Both phases are bounded by wall-clock sleeps, never by an unbounded
 * poll: docs/09-roadmap.md §11.1 makes a silent hang the worst possible
 * failure mode, so both run out of iterations and report which phase
 * timed out.
 */

